// Merges i18n/he-*.json into he-dict.js (the HE dictionary inlined by build.js).
const fs = require("fs");
const dir = __dirname + "/i18n";
const HE = {};
for (const f of fs.readdirSync(dir).filter((f) => /^he-.*\.json$/.test(f)).sort()) Object.assign(HE, JSON.parse(fs.readFileSync(dir + "/" + f, "utf8")));
HE["بوابة الخريجين"] = HE["بوابة الخريجين"] || "פורטל הבוגרים";
fs.writeFileSync(__dirname + "/he-dict.js", "// Arabic → Hebrew interface strings (generated by i18n-merge.js from i18n/he-*.json).\nconst HE = " + JSON.stringify(HE) + ";\n");
console.log(Object.keys(HE).length, "entries");
